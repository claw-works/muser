"""Generate the sub-skill documents under skills/.

Parameter names, ranges, defaults, units, descriptions, placement advice and examples all come from
the description tables in the code (`muser effects --json` / `muser instruments --json`), so the
documents stay consistent with the code. This script only adds the hand-written scenario presets and
tips. After the description tables in the code change, run it again:

    scripts/gen_skills.py [path/to/muser]

The script puts every scenario preset into a temporary project and hands it to `muser validate`, so an
out-of-range preset fails immediately.
"""

