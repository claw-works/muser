def params_section(family, items, examples=True):
    # Instruments of one family share the same parameter table (except drum kits); take the first as representative and list each one's current values.
    infos = [describe(i["name"]) for i in items]
    rep = infos[0]
    if not rep["params"]:
        return ""
    lines = ["\n## Adjustable parameters (instrument_params)\n\n",
             "Override the sound of the chosen instrument/preset; write only the items you want to change, the rest stay as they are. `muser instruments <name>` shows the preset's current values.\n\n"]
    if family == "drums":
        # params_note comes from the muser binary ("Drum keys supported by this kit: ..." is the part to drop).
        lines.append(rep["params_note"].split("Drum keys supported by this kit")[0].strip() + "\n\n")
        lines.append("Each drum piece is adjustable (when automating, write `piece.parameter`, such as `kick.tune`; it takes effect from the next hit):\n\n| Parameter | Range | Automation | Description |\n|---|---|---|---|\n")
        for p in rep["params"]:
            lines.append(f"| `{p['name']}` | {fmt_range(p)} | {AUTO_LABEL[p['automation']]} | {p['description']} |\n")
    else:
        lines.append("| Parameter | Range | Automation | Description |\n|---|---|---|---|\n")
        for p in rep["params"]:
            lines.append(f"| `{p['name']}` | {fmt_range(p)} | {AUTO_LABEL[p['automation']]} | {p['description']} |\n")
        lines.append("\nAutomation column: ✓ = notes already sounding follow immediately; next note = affects only notes that start afterward; — = cannot be automated. See [automation.md](../automation.md).\n")
        if family != "synth_one":
            names = [p["name"] for p in rep["params"]]
            lines.append("\nPreset values of each instrument:\n\n| instrument | " + " | ".join(f"`{n}`" for n in names) + " |\n|---|" + "---|" * len(names) + "\n")
            for info in infos:
                cur = {p["name"]: p["current"] for p in info["params"]}
                if [p["name"] for p in info["params"]] != names:
                    continue
                lines.append(f"| `{info['name']}` | " + " | ".join(fmt_val(cur[n]) for n in names) + " |\n")
    ex = PARAM_EXAMPLES.get(family, []) if examples else []
    if ex:
        lines.append("\n### Tuning examples\n\n")
        for title, inst, params in ex:
            lines.append(f"- {title}\n\n  ```json\n  {{ \"instrument\": \"{inst}\", \"instrument_params\": {json.dumps(params, ensure_ascii=False)} }}\n  ```\n\n")
    return "".join(lines)


