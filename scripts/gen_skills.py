def automation_page():
    lines = [HEADER, """# Automation: make parameters change over time

Automation makes instrument parameters, effect parameters, gain and pan change during playback: filter sweeps, fade-ins and fade-outs, pan swings,
seeded random walks. The time unit is the **beat**, counted from the start of the project, same as notes; values use the parameter's own unit (Hz, seconds, dB...).

## Where to write it

- A track's `automation`: targets `instrument` (instrument parameters), `effects[i]` (the i-th effect of that track, starting at 0), `gain_db`, `pan`,
  `sends.<bus>` (send amount in dB; that bus must already be written in `sends`).
- A bus's `automation`: targets `effects[i]`, `gain_db`, `pan`, `sends.<bus>` (see [routing.md](routing.md)).
- The project's `automation`: targets `master_gain_db`, `master_effects[i]`.
- For an effect that works only for a period (connected or removed midway): write `"from"` / `"until"` (beats) on the effect. Before it, nothing is processed (the state is empty, as if plugged in midway),
  and after it, it is removed (the tail is cut off); for a gradual fade in or out, automate `mix`.

```json
{
  "tempo": 128,
  "seed": 7,
  "master_effects": [{ "type": "reverb", "mix": 0.05 }],
  "automation": [ %s ],
  "tracks": [{
    "instrument": "bass.acid",
    "automation": [
      { "target": "instrument", "param": "cutoff", "shape": "points", "points": [[0, 200], [32, 4000]], "curve": "exp" }
    ],
    "clips": [ ... ]
  }]
}
```

`param` has the same name as in `instrument_params` / the effect's parameters; for a drum kit write `piece.parameter` (such as `kick.tune`); omit it when the target is `gain_db` / `pan` /
`master_gain_db`. Which parameters can be automated and when changes take effect: see the notes in `muser instruments <name>`,
or the "automation" column of the parameter table in each instrument sub-skill.

## Three shapes

### points: a curve through time points

```json
{ "shape": "points", "points": [[0, 200], [16, 3000], [32, 800]], "curve": "exp" }
```

- `points`: `[beat, value]`, with time strictly increasing. Before the first point the first value is used, and after the last point the last value is held.
- `curve`: `linear` (default, straight line), `exp` (changes proportionally, so frequency/time-type parameters sound more even; requires adjacent points of the same sign and nonzero),
  `smooth` (S-shaped, flat at both ends), `step` (hold the previous value until the next point, for "switching").
- A value can be written as a name the parameter allows, such as the choir vowels `"a"` `"o"`.

### lfo: periodic swing

```json
{ "shape": "lfo", "wave": "sine", "period_beats": 4, "min": -0.5, "max": 0.5, "phase": 0 }
```

- `wave`: `sine` (default) / `triangle` / `saw` (rises from min to max, then jumps back) / `square` (switches between min and max).
- `period_beats`: how many beats in one period. 4 = once per bar (4/4), 1 = once per beat, 0.5 = once per eighth note. Counted in beats, so it follows the tempo.
- `phase`: starting phase 0-1; `sine` starts from min at 0.

### random: seeded random

```json
{ "shape": "random", "style": "walk", "step_beats": 0.5, "min": 200, "max": 2500, "max_step": 0.2 }
```

- `style`: `jump` (jump to a new random value on each step) / `glide` (default, glide smoothly to the new value) / `walk` (random walk: each step moves near the current value,
  by at most `max_step` x the range).
- `step_beats`: how many beats between changes of the target value.
- `seed` (optional): when omitted, it is derived from the project `seed` and the position of this automation. **The same seed renders exactly the same every time; changing the project `seed`
  gives a different random variation**, which suits "render several versions and pick one".

## Active range

`start` / `end` (beats, optional) limit the time during which the automation is active; outside the range the parameter returns to its static value (the value written in `instrument_params` or the effect).
The phase of `lfo` / `random` and the random sequence are counted from `start`.

## Behavior notes

- Instrument and effect parameters update every 64 frames (about 1.3 ms at 48 kHz); gain and pan update per frame, so fades have no steps.
- Parameters that "take effect on the next note" (such as a bowed string's vibrato, a drum piece's tuning) affect only notes that start after the automation; notes already sounding do not change.
- Several automations on the same target: effect/instrument parameters are written in order, with later ones overriding earlier ones; for `gain_db` / `pan` the value of the last one active in its range is used.
- A value outside the parameter's range, a wrong parameter name, or a parameter that cannot be automated (switches, options, integers): `muser validate` points out the exact location in every case.
- External plugin parameters can be automated too: write the plugin parameter name in `param`, and the value can be the text the plugin displays (such as `[[0, "200 Hz"], [16, "4000 Hz"]]`) or a number (plugin automation scale).
  The plugin receives the new value on the first frame of the next processing block (block length <= 64 frames). Parameter automation for `sfz:` instruments is not supported yet.

## Examples

""" % json.dumps(MASTER_EXAMPLE, ensure_ascii=False)]
