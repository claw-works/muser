def fmt_range(p):
    t = p["type"]
    if t == "number":
        unit = f" {p['unit']}" if p["unit"] else ""
        r = f"{fmt_num(p['min'])} – {fmt_num(p['max'])}{unit}"
        if p.get("integer"):
            r += " (integer)"
        if p.get("names"):
            r += ", or " + " / ".join(f"`\"{n}\"`" for n in p["names"])
        return r
    if t == "choice":
        return " / ".join(f"`\"{c}\"`" for c in p["choices"])
    if t == "bool":
        return "`true` / `false`"
    if t == "drawbars":
        return "A string of 9 digits, each 0-8"
    return ""


