def pedal_page():
    lines = [HEADER, """# Sustain pedal (pedal)

A clip's `pedal` is the list of **depressed intervals** of the sustain pedal (MIDI CC64): `[[start, end], ...]`, in beats, relative to the clip start, increasing in time and non-overlapping.

- Keys released while the pedal is down keep sounding, and all enter release together when the pedal comes up; new notes pressed while it is down are held in the same way.
- Supported: the built-in synths (`poly.*`, `synth.*`, electric piano, strings, etc.), the SFZ sampler (`sfz:`), and plugin instruments (`plugin:`, CC64 is forwarded and handled by the plugin). Drum kits ignore it.
- Order at the same instant: release keys -> pedal up -> pedal down -> press new notes. So "the previous interval ends at 4.0 and the next starts at 4.0" also changes the pedal correctly.
- An interval beyond the end of the clip is cut at the clip end; mistakes (reversed order, overlap, start beyond the clip) report the location, such as `tracks[0].clips[0].pedal[1]`.
- MCP: `add_clip` can carry `pedal`, or use `set_pedal` to replace the pedal of a clip as a whole.

## How to pedal

- **Write notes at their real durations and leave the sustain to the pedal.** Do not lengthen each note to imitate the pedal: with a real pedal, all notes stop together when it lifts, which sounds more like a piano.
- **Change the pedal when the chord changes**, using syncopated pedaling (legato pedal): press it down shortly after the first note of the new chord is played (about 0.05-0.1 beat), and the previous interval continues until a moment later before lifting.
  Lifting first and then playing cuts the sound off; pressing down before playing drags the old chord in.
- You can hold it down throughout the same harmony; when the harmony changes you must change it, otherwise it gets muddy.
- The low register gets muddy more easily than the high register: in passages where the bass moves fast, change more often, or pedal only on long notes.
- Do not pedal staccato and short-note passages.
- Electric piano and pad can also use the pedal to hold chords; when the synth's release is very long, the pedal's effect is not obvious.
- The pedal only extends notes already played, and does not simulate the sympathetic resonance of unplayed strings; when you need a more open feel, add a little reverb (send to a reverb bus).

## Examples

Each example is one clip (put it in a track's `clips`), and all pass `muser validate`:
"""]
