def fmt_num(v):
    return str(int(v)) if float(v).is_integer() else str(v)


def effect_page(spec):
    extra = EFFECT_EXTRA[spec["name"]]
    lines = [HEADER, f"# Effect: {spec['name']}\n\n", f"{spec['summary']}\n\n"]
    lines.append(f"**Where to put it**: {spec['placement']}\n\n")
    lines.append(f"Latest parameters: `muser effects {spec['name']}` (MCP: `describe_effect`)\n\n")
    if spec["params"] or spec["choices"]:
        lines.append("## Parameters\n\n| Parameter | Default | Range | Description |\n|---|---|---|---|\n")
        for c in spec["choices"]:
            lines.append(f"| `{c['name']}` | `{c['default']}` | {' / '.join('`'+x+'`' for x in c['choices'])} | {c['description']} |\n")
        for p in spec["params"]:
            unit = f" {p['unit']}" if p["unit"] else ""
            lines.append(f"| `{p['name']}` | {fmt_num(p['default'])} | {fmt_num(p['min'])} – {fmt_num(p['max'])}{unit} | {p['description']} |\n")
        lines.append("\nAll parameters can be omitted and take their default when omitted; when a value is out of range, `muser validate` reports the exact location.\n\n")
    else:
        lines.append("## Fields\n\n| Field | Description |\n|---|---|\n| `path` | Required, absolute path of the plugin file or bundle (.vst3 / .clap / .lv2) |\n| `id` | Optional, plugin id |\n| `params` | Optional, `{ parameter id: value }` |\n\n")
    lines.append(f"## Minimal example\n\n```json\n{spec['example']}\n```\n\n")
    if extra["presets"]:
        lines.append("## Scenario presets\n\n")
        for title, preset in extra["presets"]:
            lines.append(f"- {title}\n\n  ```json\n  {json.dumps(preset, ensure_ascii=False)}\n  ```\n\n")
    lines.append("## Tips and common mistakes\n\n")
    for t in extra["tips"]:
        lines.append(f"- {t}\n")
    return "".join(lines)


