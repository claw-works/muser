//! yinse 自己的打击乐：每件是一组衰减的振动模式（鼓皮、锣面、钹、木头各有各的频率比）加一阵敲击的噪声，
//! 锣的音高在敲下去之后滑动（大锣往下"哐～"，小锣往上"镗儿"）。不经 manguebyte 的鼓组模型。
//!
//! 第一套是锣鼓 `yinse.strike.luogu`：大鼓、堂鼓、鼓边、板鼓、拍板、大锣、小锣、大钹（含闷击）、小钹、
//! 木鱼（高、低）、梆子、碰铃。每件一个 MIDI 键（见 [`LUOGU`]），在网格里也可以写名字（`daluo` `xiaoluo` …）。

use core::f64::consts::TAU;

use manguebyte::prelude::{AudioBuffer, NoteRef, ProcessSpec};

/// 一件打击乐的设计。
#[derive(Debug, PartialEq)]
pub struct PieceDef {
    /// 名字（网格行名、`instrument_params` 的键）与中文名。
    pub name: &'static str,
    pub zh: &'static str,
    pub key: u8,
    /// 基频（Hz）与模式：(频率比, 振幅, 衰减到 -60 dB 的秒数)。
    pub f0: f64,
    pub modes: &'static [(f64, f64, f64)],
    /// 敲下去之后音高滑多少半音、用多久（锣）。
    pub glide: f64,
    pub glide_s: f64,
    /// 敲击的噪声：多响、频带（Hz）、衰减时间常数（秒）。
    pub noise: f64,
    pub noise_lo: f64,
    pub noise_hi: f64,
    pub noise_s: f64,
    /// 同组的互相掐断（钹的闷击掐住正在响的钹），0 不掐。
    pub choke: u8,
    /// 整体增益（各件响度大致拉平）。
    pub gain: f64,
    /// 默认声像。
    pub pan: f64,
    /// 噪声分几下打出来（拍手：几只手前后差 10 ms 左右），最后一下接着按 `noise_s` 衰减；0 / 1 只有一下。
    pub bursts: u8,
    /// 分频带的噪声层（ride：模态之间那一片密的"沙"，鼓槌的"嗒"也是一层）；空的没有。同一件连着敲共用一组（见 [`Wash`]）。
    pub layers: &'static [NoiseLayer],
    /// 每个模态起振的相位（弧度，与 `modes` 一一对应）；空的都从零相位起。量出来的波形（底鼓头几十毫秒的那一下）靠它对上。
    pub phases: &'static [f64],
    /// 左右去相关多少（像头顶话筒收的一片镲，不是一个点）：0 两边一样，1 完全不相关（ride），0.45 左右的相关系数 0.7（踩镲）。
    /// 每个模态左右差一个固定的相位（最多 ±π·width），每一下的起始相位随机；噪声层左右一部分共用、一部分各出各的。
    pub width: f64,
    /// 共振的音量随力度的几次方（默认 1.4）；大了轻敲时只剩敲击声（ride 的钟面）。
    pub mode_vel: f64,
    /// 共振涌起来用多久（秒，0 一敲就满）：从四分之一涌到满（sizzle 吊镲的金属声是敲下去以后才起来的）。
    pub mode_attack: f64,
}

/// 一层带通噪声：频带（Hz），快、慢两段衰减各自多响（相对模态里最响的那个）与时间常数（秒），声像相对这一件偏多少。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct NoiseLayer {
    pub lo: f64,
    pub hi: f64,
    pub fast: f64,
    pub fast_s: f64,
    pub slow: f64,
    pub slow_s: f64,
    pub pan: f64,
    /// 上沿用四阶低通（二阶的会漏到上面的频带里；底鼓 9 kHz 以上几乎没有东西）。
    pub steep: bool,
}

const fn layer(lo: f64, hi: f64, fast: (f64, f64), slow: (f64, f64), pan: f64) -> NoiseLayer {
    NoiseLayer { lo, hi, fast: fast.0, fast_s: fast.1, slow: slow.0, slow_s: slow.1, pan, steep: false }
}

/// 上沿收得陡的一层（见 [`NoiseLayer::steep`]）。
const fn steep_layer(lo: f64, hi: f64, fast: (f64, f64), slow: (f64, f64)) -> NoiseLayer {
    NoiseLayer { lo, hi, fast: fast.0, fast_s: fast.1, slow: slow.0, slow_s: slow.1, pan: 0.0, steep: true }
}

